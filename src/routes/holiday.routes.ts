import { Router } from "express";
import * as holidayController from "../controllers/holiday.controller";
import { asyncWrapper } from "../helpers/asyncWrapper";
import { verifyToken } from "../middleware/auth";
import { requireSchoolAccess } from "../middleware/roleGuard";
import { validate } from "../middleware/validate";
import {
  createHolidaySchema,
  holidayIdParamSchema,
  listHolidaysSchema,
  updateHolidaySchema
} from "../validators/holiday.validator";

export const holidayRoutes = Router();

holidayRoutes.use(verifyToken, requireSchoolAccess);

holidayRoutes.get("/", validate(listHolidaysSchema), asyncWrapper(holidayController.listHolidays));

holidayRoutes.post(
  "/",
  validate(createHolidaySchema),
  asyncWrapper(holidayController.createHoliday)
);

holidayRoutes.get(
  "/:id",
  validate({ params: holidayIdParamSchema }),
  asyncWrapper(holidayController.getHoliday)
);

holidayRoutes.patch(
  "/:id",
  validate(updateHolidaySchema),
  asyncWrapper(holidayController.updateHoliday)
);

holidayRoutes.delete(
  "/:id",
  validate({ params: holidayIdParamSchema }),
  asyncWrapper(holidayController.deleteHoliday)
);
