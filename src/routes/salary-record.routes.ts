import { Router } from "express";
import * as salaryController from "../controllers/staff/salary.controller";
import { asyncWrapper } from "../helpers/asyncWrapper";
import { verifyToken } from "../middleware/auth";
import { requireSchoolAccess } from "../middleware/roleGuard";
import { validate } from "../middleware/validate";
import {
  createSalarySchema,
  listSalarySchema,
  markSalaryPaidSchema,
  salaryRecordIdParamSchema,
  updateSalarySchema
} from "../validators/staff/salary.validator";

export const salaryRecordRoutes = Router();

salaryRecordRoutes.use(verifyToken, requireSchoolAccess);

salaryRecordRoutes.get(
  "/",
  validate(listSalarySchema),
  asyncWrapper(salaryController.listSalaryRecords)
);

salaryRecordRoutes.post(
  "/",
  validate(createSalarySchema),
  asyncWrapper(salaryController.createSalaryRecord)
);

salaryRecordRoutes.get(
  "/:id",
  validate({ params: salaryRecordIdParamSchema }),
  asyncWrapper(salaryController.getSalaryRecord)
);

salaryRecordRoutes.patch(
  "/:id",
  validate(updateSalarySchema),
  asyncWrapper(salaryController.updateSalaryRecord)
);

salaryRecordRoutes.delete(
  "/:id",
  validate({ params: salaryRecordIdParamSchema }),
  asyncWrapper(salaryController.deleteSalaryRecord)
);

salaryRecordRoutes.patch(
  "/:id/mark-paid",
  validate(markSalaryPaidSchema),
  asyncWrapper(salaryController.markSalaryPaid)
);
