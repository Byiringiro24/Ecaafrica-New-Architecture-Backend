import { Router } from "express";
import * as subjectController from "../controllers/subject.controller";
import { asyncWrapper } from "../helpers/asyncWrapper";
import { verifyToken } from "../middleware/auth";
import { requireSchoolAccess } from "../middleware/roleGuard";
import { validate } from "../middleware/validate";
import {
  createSubjectSchema,
  listSubjectsSchema,
  subjectIdParamSchema,
  updateSubjectSchema
} from "../validators/subject.validator";

export const subjectRoutes = Router();

subjectRoutes.use(verifyToken, requireSchoolAccess);

subjectRoutes.get("/", validate(listSubjectsSchema), asyncWrapper(subjectController.listSubjects));

subjectRoutes.post(
  "/",
  validate(createSubjectSchema),
  asyncWrapper(subjectController.createSubject)
);

subjectRoutes.get(
  "/:id",
  validate({ params: subjectIdParamSchema }),
  asyncWrapper(subjectController.getSubject)
);

subjectRoutes.patch(
  "/:id",
  validate(updateSubjectSchema),
  asyncWrapper(subjectController.updateSubject)
);

subjectRoutes.delete(
  "/:id",
  validate({ params: subjectIdParamSchema }),
  asyncWrapper(subjectController.deleteSubject)
);
