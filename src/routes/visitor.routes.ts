import { Router } from "express";
import * as visitorController from "../controllers/visitor.controller";
import { asyncWrapper } from "../helpers/asyncWrapper";
import { verifyToken } from "../middleware/auth";
import { requireSchoolAccess } from "../middleware/roleGuard";
import { validate } from "../middleware/validate";
import {
  createVisitorSchema,
  listVisitorsSchema,
  updateVisitorSchema,
  visitorIdParamSchema
} from "../validators/visitor.validator";

export const visitorRoutes = Router();

visitorRoutes.use(verifyToken, requireSchoolAccess);

visitorRoutes.get(
  "/",
  validate(listVisitorsSchema),
  asyncWrapper(visitorController.listVisitors)
);

visitorRoutes.post(
  "/",
  validate(createVisitorSchema),
  asyncWrapper(visitorController.createVisitor)
);

visitorRoutes.get(
  "/:id",
  validate({ params: visitorIdParamSchema }),
  asyncWrapper(visitorController.getVisitor)
);

visitorRoutes.patch(
  "/:id",
  validate(updateVisitorSchema),
  asyncWrapper(visitorController.updateVisitor)
);

visitorRoutes.delete(
  "/:id",
  validate({ params: visitorIdParamSchema }),
  asyncWrapper(visitorController.deleteVisitor)
);
