import { Router } from "express";
import * as subscriptionController from "../../controllers/platform/subscription.controller";
import { asyncWrapper } from "../../helpers/asyncWrapper";
import { verifyPlatformToken } from "../../middleware/auth";
import { requireRole } from "../../middleware/roleGuard";
import { validate } from "../../middleware/validate";
import { PlatformRole } from "../../constants/roles";
import {
  createSubscriptionSchema,
  listSubscriptionsSchema,
  subscriptionIdParamSchema,
  updateSubscriptionSchema
} from "../../validators/platform/subscription.validator";

export const subscriptionRoutes = Router();

subscriptionRoutes.use(verifyPlatformToken, requireRole(PlatformRole.PLATFORM_ADMIN));

subscriptionRoutes.get(
  "/",
  validate(listSubscriptionsSchema),
  asyncWrapper(subscriptionController.listSubscriptions)
);

subscriptionRoutes.post(
  "/",
  validate(createSubscriptionSchema),
  asyncWrapper(subscriptionController.createSubscription)
);

subscriptionRoutes.get(
  "/:id",
  validate({ params: subscriptionIdParamSchema }),
  asyncWrapper(subscriptionController.getSubscription)
);

subscriptionRoutes.patch(
  "/:id",
  validate(updateSubscriptionSchema),
  asyncWrapper(subscriptionController.updateSubscription)
);

subscriptionRoutes.delete(
  "/:id",
  validate({ params: subscriptionIdParamSchema }),
  asyncWrapper(subscriptionController.deleteSubscription)
);
