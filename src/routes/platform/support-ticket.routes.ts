import { Router } from "express";
import * as supportTicketController from "../../controllers/platform/support-ticket.controller";
import { asyncWrapper } from "../../helpers/asyncWrapper";
import { verifyPlatformToken } from "../../middleware/auth";
import { requireRole } from "../../middleware/roleGuard";
import { validate } from "../../middleware/validate";
import { PlatformRole } from "../../constants/roles";
import {
  createSupportTicketMessageSchema,
  createSupportTicketSchema,
  listSupportTicketsSchema,
  supportTicketIdParamSchema,
  supportTicketMessageIdParamSchema,
  updateSupportTicketMessageSchema,
  updateSupportTicketSchema
} from "../../validators/platform/support-ticket.validator";

export const supportTicketRoutes = Router();

supportTicketRoutes.use(verifyPlatformToken, requireRole(PlatformRole.PLATFORM_ADMIN));

supportTicketRoutes.get(
  "/",
  validate(listSupportTicketsSchema),
  asyncWrapper(supportTicketController.listSupportTickets)
);

supportTicketRoutes.post(
  "/",
  validate(createSupportTicketSchema),
  asyncWrapper(supportTicketController.createSupportTicket)
);

supportTicketRoutes.get(
  "/:id",
  validate({ params: supportTicketIdParamSchema }),
  asyncWrapper(supportTicketController.getSupportTicket)
);

supportTicketRoutes.patch(
  "/:id",
  validate(updateSupportTicketSchema),
  asyncWrapper(supportTicketController.updateSupportTicket)
);

supportTicketRoutes.delete(
  "/:id",
  validate({ params: supportTicketIdParamSchema }),
  asyncWrapper(supportTicketController.deleteSupportTicket)
);

supportTicketRoutes.get(
  "/:id/messages",
  validate({ params: supportTicketIdParamSchema }),
  asyncWrapper(supportTicketController.listSupportTicketMessages)
);

supportTicketRoutes.post(
  "/:id/messages",
  validate(createSupportTicketMessageSchema),
  asyncWrapper(supportTicketController.createSupportTicketMessage)
);

supportTicketRoutes.get(
  "/:id/messages/:messageId",
  validate({ params: supportTicketMessageIdParamSchema }),
  asyncWrapper(supportTicketController.getSupportTicketMessage)
);

supportTicketRoutes.patch(
  "/:id/messages/:messageId",
  validate(updateSupportTicketMessageSchema),
  asyncWrapper(supportTicketController.updateSupportTicketMessage)
);

supportTicketRoutes.delete(
  "/:id/messages/:messageId",
  validate({ params: supportTicketMessageIdParamSchema }),
  asyncWrapper(supportTicketController.deleteSupportTicketMessage)
);
