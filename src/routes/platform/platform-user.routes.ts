import { Router } from "express";
import * as platformUserController from "../../controllers/platform/platform-user.controller";
import { asyncWrapper } from "../../helpers/asyncWrapper";
import { verifyPlatformToken } from "../../middleware/auth";
import { requireRole } from "../../middleware/roleGuard";
import { validate } from "../../middleware/validate";
import { PlatformRole } from "../../constants/roles";
import {
  createPlatformUserSchema,
  listPlatformUsersSchema,
  platformUserIdParamSchema,
  updatePlatformUserSchema
} from "../../validators/platform/platform-user.validator";

export const platformUserRoutes = Router();

platformUserRoutes.use(verifyPlatformToken, requireRole(PlatformRole.PLATFORM_ADMIN));

platformUserRoutes.get(
  "/",
  validate(listPlatformUsersSchema),
  asyncWrapper(platformUserController.listPlatformUsers)
);

platformUserRoutes.post(
  "/",
  validate(createPlatformUserSchema),
  asyncWrapper(platformUserController.createPlatformUser)
);

platformUserRoutes.get(
  "/:id",
  validate({ params: platformUserIdParamSchema }),
  asyncWrapper(platformUserController.getPlatformUser)
);

platformUserRoutes.patch(
  "/:id",
  validate(updatePlatformUserSchema),
  asyncWrapper(platformUserController.updatePlatformUser)
);

platformUserRoutes.delete(
  "/:id",
  validate({ params: platformUserIdParamSchema }),
  asyncWrapper(platformUserController.deletePlatformUser)
);
