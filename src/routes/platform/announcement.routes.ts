import { Router } from "express";
import * as announcementController from "../../controllers/platform/announcement.controller";
import { asyncWrapper } from "../../helpers/asyncWrapper";
import { verifyPlatformToken } from "../../middleware/auth";
import { requireRole } from "../../middleware/roleGuard";
import { validate } from "../../middleware/validate";
import { PlatformRole } from "../../constants/roles";
import {
  announcementIdParamSchema,
  createAnnouncementSchema,
  listAnnouncementsSchema,
  markAnnouncementReadSchema,
  updateAnnouncementSchema
} from "../../validators/platform/announcement.validator";

export const announcementRoutes = Router();

announcementRoutes.use(verifyPlatformToken, requireRole(PlatformRole.PLATFORM_ADMIN));

announcementRoutes.get(
  "/",
  validate(listAnnouncementsSchema),
  asyncWrapper(announcementController.listAnnouncements)
);

announcementRoutes.post(
  "/",
  validate(createAnnouncementSchema),
  asyncWrapper(announcementController.createAnnouncement)
);

announcementRoutes.get(
  "/:id",
  validate({ params: announcementIdParamSchema }),
  asyncWrapper(announcementController.getAnnouncement)
);

announcementRoutes.patch(
  "/:id",
  validate(updateAnnouncementSchema),
  asyncWrapper(announcementController.updateAnnouncement)
);

announcementRoutes.delete(
  "/:id",
  validate({ params: announcementIdParamSchema }),
  asyncWrapper(announcementController.deleteAnnouncement)
);

announcementRoutes.post(
  "/:id/read",
  validate(markAnnouncementReadSchema),
  asyncWrapper(announcementController.markAnnouncementRead)
);
