import { Router } from "express";
import * as parentController from "../controllers/parent.controller";
import { asyncWrapper } from "../helpers/asyncWrapper";
import { verifyToken } from "../middleware/auth";
import { requireSchoolAccess } from "../middleware/roleGuard";
import { validate } from "../middleware/validate";
import {
  createParentSchema,
  listParentsSchema,
  parentIdParamSchema,
  updateParentSchema
} from "../validators/parent.validator";

export const parentRoutes = Router();

parentRoutes.use(verifyToken, requireSchoolAccess);

parentRoutes.get("/", validate(listParentsSchema), asyncWrapper(parentController.listParents));

parentRoutes.post("/", validate(createParentSchema), asyncWrapper(parentController.createParent));

parentRoutes.get(
  "/:id",
  validate({ params: parentIdParamSchema }),
  asyncWrapper(parentController.getParent)
);

parentRoutes.patch(
  "/:id",
  validate(updateParentSchema),
  asyncWrapper(parentController.updateParent)
);

parentRoutes.delete(
  "/:id",
  validate({ params: parentIdParamSchema }),
  asyncWrapper(parentController.deleteParent)
);
