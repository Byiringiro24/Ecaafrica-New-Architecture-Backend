import { Router } from "express";
import * as studentController from "../controllers/student.controller";
import * as parentController from "../controllers/parent.controller";
import { asyncWrapper } from "../helpers/asyncWrapper";
import { verifyToken } from "../middleware/auth";
import { requireSchoolAccess, requireRole } from "../middleware/roleGuard";
import { validate } from "../middleware/validate";
import {
  createStudentEnrollmentSchema,
  createStudentSchema,
  listStudentEnrollmentsSchema,
  listStudentsSchema,
  studentIdParamSchema,
  updateStudentSchema,
  updateVisitorAccessSchema
} from "../validators/student.validator";
import {
  linkParentSchema,
  studentParentParamsSchema
} from "../validators/parent.validator";
import { uploadCsv, uploadStudentPhoto } from "../configs/multer";

export const studentRoutes = Router();

studentRoutes.use(verifyToken, requireSchoolAccess);

studentRoutes.get("/", validate(listStudentsSchema), asyncWrapper(studentController.listStudents));

studentRoutes.post("/", validate(createStudentSchema), asyncWrapper(studentController.createStudent));

studentRoutes.post(
  "/import",
  uploadCsv.single("file"),
  asyncWrapper(studentController.importStudentsFromCsv)
);

studentRoutes.get(
  "/:id",
  validate({ params: studentIdParamSchema }),
  asyncWrapper(studentController.getStudent)
);

studentRoutes.patch(
  "/:id",
  validate(updateStudentSchema),
  asyncWrapper(studentController.updateStudent)
);

studentRoutes.patch(
  "/:id/visitor-access",
  requireRole("school_admin"),
  validate(updateVisitorAccessSchema),
  asyncWrapper(studentController.updateVisitorAccess)
);

studentRoutes.delete(
  "/:id",
  validate({ params: studentIdParamSchema }),
  asyncWrapper(studentController.deleteStudent)
);

studentRoutes.post(
  "/:id/enrollments",
  validate(createStudentEnrollmentSchema),
  asyncWrapper(studentController.createStudentEnrollment)
);

studentRoutes.get(
  "/:id/enrollments",
  validate(listStudentEnrollmentsSchema),
  asyncWrapper(studentController.listStudentEnrollments)
);

studentRoutes.post(
  "/:id/parents",
  validate(linkParentSchema),
  asyncWrapper(parentController.linkParentToStudent)
);

studentRoutes.delete(
  "/:id/parents/:parentId",
  validate({ params: studentParentParamsSchema }),
  asyncWrapper(parentController.unlinkParentFromStudent)
);

studentRoutes.post(
  "/:id/photo",
  uploadStudentPhoto.single("photo"),
  asyncWrapper(studentController.uploadStudentPhoto)
);
