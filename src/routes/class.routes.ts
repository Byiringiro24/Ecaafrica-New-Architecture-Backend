import { Router } from "express";
import * as classController from "../controllers/class.controller";
import { asyncWrapper } from "../helpers/asyncWrapper";
import { verifyToken } from "../middleware/auth";
import { requireSchoolAccess } from "../middleware/roleGuard";
import { validate } from "../middleware/validate";
import {
  classIdParamSchema,
  createClassSchema,
  listClassesSchema,
  updateClassSchema
} from "../validators/class.validator";

export const classRoutes = Router();

classRoutes.use(verifyToken, requireSchoolAccess);

classRoutes.get("/", validate(listClassesSchema), asyncWrapper(classController.listClasses));

classRoutes.post(
  "/",
  validate(createClassSchema),
  asyncWrapper(classController.createClass)
);

classRoutes.get(
  "/:id",
  validate({ params: classIdParamSchema }),
  asyncWrapper(classController.getClass)
);

classRoutes.patch(
  "/:id",
  validate(updateClassSchema),
  asyncWrapper(classController.updateClass)
);

classRoutes.delete(
  "/:id",
  validate({ params: classIdParamSchema }),
  asyncWrapper(classController.deleteClass)
);
